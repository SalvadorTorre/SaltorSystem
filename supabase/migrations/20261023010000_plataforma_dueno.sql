-- Plataforma: opcion del menu solo para el dueno del sistema.
--
--  * myappdb.plataforma_duenos: quien es dueno (por correo o por codusuario).
--  * Empresas activas / suspendidas (una empresa suspendida no puede entrar).
--  * RPCs de la plataforma, todas validan que quien llama sea el dueno:
--      plataforma_es_dueno()               -> boolean
--      plataforma_listar_empresas()        -> empresas con resumen
--      plataforma_cambiar_estado_empresa() -> activar / suspender
--      plataforma_entrar_empresa()         -> el dueno trabaja como otra empresa
--      empresa_estado_acceso()             -> usado al iniciar sesion
--  * Solo el dueno puede crear, editar o borrar empresas.

begin;

-- 1) Duenos de la plataforma -------------------------------------------------
create table if not exists myappdb.plataforma_duenos (
  id bigint generated by default as identity primary key,
  correo text,
  codusuario integer,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint plataforma_duenos_identidad check (correo is not null or codusuario is not null)
);

create unique index if not exists plataforma_duenos_correo_unq
  on myappdb.plataforma_duenos (lower(correo)) where correo is not null;
create unique index if not exists plataforma_duenos_codusuario_unq
  on myappdb.plataforma_duenos (codusuario) where codusuario is not null;

-- Nadie la lee ni la modifica desde la API; solo las funciones de abajo.
alter table myappdb.plataforma_duenos enable row level security;
revoke all on table myappdb.plataforma_duenos from anon, authenticated;

-- Dueno inicial. Si inicias sesion con otro correo o usuario, agregalo asi:
--   insert into myappdb.plataforma_duenos (correo) values ('otro@correo.com');
--   insert into myappdb.plataforma_duenos (codusuario) values (123);
insert into myappdb.plataforma_duenos (correo)
select 'saltorsystem@gmail.com'
where not exists (
  select 1 from myappdb.plataforma_duenos where lower(correo) = 'saltorsystem@gmail.com'
);

-- Los usuarios del sistema que tengan ese correo tambien quedan como duenos.
insert into myappdb.plataforma_duenos (codusuario)
select u.codusuario
from myappdb.usuario u
where lower(coalesce(u.correo, '')) = 'saltorsystem@gmail.com'
  and not exists (
    select 1 from myappdb.plataforma_duenos d where d.codusuario = u.codusuario
  );

create or replace function app_private.es_dueno_plataforma()
returns boolean
language sql
stable
security definer
set search_path = myappdb, public
as $$
  select exists (
    select 1
    from myappdb.plataforma_duenos d
    where d.activo
      and auth.uid() is not null
      and (
        (d.correo is not null and lower(d.correo) = lower(coalesce(auth.jwt()->>'email', '')))
        or (d.codusuario is not null and d.codusuario = (
              select cu.codusuario from app_private.current_usuario() cu limit 1))
        or (d.correo is not null and exists (
              select 1
              from app_private.current_usuario() cu
              join myappdb.usuario u on u.codusuario = cu.codusuario
              where lower(coalesce(u.correo, '')) = lower(d.correo)))
      )
  );
$$;

revoke all on function app_private.es_dueno_plataforma() from public;
grant execute on function app_private.es_dueno_plataforma() to authenticated;

create or replace function myappdb.plataforma_es_dueno()
returns boolean
language sql
stable
security definer
set search_path = myappdb, public
as $$
  select app_private.es_dueno_plataforma();
$$;

revoke all on function myappdb.plataforma_es_dueno() from public;
grant execute on function myappdb.plataforma_es_dueno() to authenticated;

-- 2) Estado de la empresa ----------------------------------------------------
alter table myappdb.empresas add column if not exists activa boolean not null default true;
alter table myappdb.empresas add column if not exists fecha_suspension timestamptz;
alter table myappdb.empresas add column if not exists motivo_suspension text;

comment on column myappdb.empresas.activa is 'false = empresa suspendida desde Plataforma; sus usuarios no pueden entrar.';

-- 3) Solo el dueno crea, edita o borra empresas -------------------------------
do $$
begin
  if exists (
    select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'myappdb' and c.relname = 'empresas' and c.relrowsecurity
  ) then
    execute 'drop policy if exists empresas_insert_solo_dueno on myappdb.empresas';
    execute 'drop policy if exists empresas_update_solo_dueno on myappdb.empresas';
    execute 'drop policy if exists empresas_delete_solo_dueno on myappdb.empresas';
    execute 'create policy empresas_insert_solo_dueno on myappdb.empresas as restrictive
             for insert to authenticated with check (app_private.es_dueno_plataforma())';
    execute 'create policy empresas_update_solo_dueno on myappdb.empresas as restrictive
             for update to authenticated using (app_private.es_dueno_plataforma())
             with check (app_private.es_dueno_plataforma())';
    execute 'create policy empresas_delete_solo_dueno on myappdb.empresas as restrictive
             for delete to authenticated using (app_private.es_dueno_plataforma())';
  end if;
end;
$$;

-- 4) Listado de empresas con resumen ----------------------------------------
create or replace function myappdb.plataforma_listar_empresas()
returns jsonb
language plpgsql
stable
security definer
set search_path = myappdb, public
as $$
declare
  v_desde date := date_trunc('month', current_date)::date;
  v_result jsonb;
begin
  if not app_private.es_dueno_plataforma() then
    raise exception 'Solo el dueno de la plataforma puede usar esta opcion.' using errcode = '42501';
  end if;

  with suc as (
    select s.cod_empre::text as cod_empre, count(*) as sucursales
    from myappdb.sucursales s group by s.cod_empre
  ),
  usu as (
    select u.cod_empre::text as cod_empre, count(*) as usuarios
    from myappdb.usuario u group by u.cod_empre
  ),
  ven as (
    select f.fa_codempr::text as cod_empre,
           count(*) as facturas_mes,
           coalesce(sum(f.fa_valfact), 0) as ventas_mes,
           max(f.fa_fecfact) as ultima_factura
    from myappdb.factura f
    where f.fa_fecfact >= v_desde
      and (f.fa_status is null or f.fa_status <> 'N')
    group by f.fa_codempr
  )
  select coalesce(jsonb_agg(
           to_jsonb(e)
           || jsonb_build_object(
                'sucursales', coalesce(suc.sucursales, 0),
                'usuarios', coalesce(usu.usuarios, 0),
                'facturas_mes', coalesce(ven.facturas_mes, 0),
                'ventas_mes', coalesce(ven.ventas_mes, 0),
                'ultima_factura', ven.ultima_factura
              )
           order by e.nom_empre
         ), '[]'::jsonb)
    into v_result
  from myappdb.empresas e
  left join suc on suc.cod_empre = e.cod_empre::text
  left join usu on usu.cod_empre = e.cod_empre::text
  left join ven on ven.cod_empre = e.cod_empre::text;

  return v_result;
end;
$$;

revoke all on function myappdb.plataforma_listar_empresas() from public;
grant execute on function myappdb.plataforma_listar_empresas() to authenticated;

-- 5) Activar / suspender -----------------------------------------------------
create or replace function myappdb.plataforma_cambiar_estado_empresa(
  p_cod_empre text,
  p_activa boolean,
  p_motivo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = myappdb, public
as $$
declare
  v_row myappdb.empresas%rowtype;
begin
  if not app_private.es_dueno_plataforma() then
    raise exception 'Solo el dueno de la plataforma puede usar esta opcion.' using errcode = '42501';
  end if;

  update myappdb.empresas e
     set activa = coalesce(p_activa, true),
         fecha_suspension = case when coalesce(p_activa, true) then null else now() end,
         motivo_suspension = case when coalesce(p_activa, true) then null
                                  else nullif(btrim(coalesce(p_motivo, '')), '') end
   where e.cod_empre = btrim(coalesce(p_cod_empre, ''))
  returning * into v_row;

  if not found then
    raise exception 'La empresa % no existe.', p_cod_empre using errcode = 'P0001';
  end if;

  return to_jsonb(v_row);
end;
$$;

revoke all on function myappdb.plataforma_cambiar_estado_empresa(text, boolean, text) from public;
grant execute on function myappdb.plataforma_cambiar_estado_empresa(text, boolean, text) to authenticated;

-- 6) Entrar como otra empresa ------------------------------------------------
-- Cambia la empresa y sucursal del usuario del dueno. Todo el sistema (pantallas
-- y politicas) toma la empresa de myappdb.usuario, asi que despues de esto el
-- dueno trabaja dentro de esa empresa hasta que cambie otra vez.
create or replace function myappdb.plataforma_entrar_empresa(
  p_cod_empre text,
  p_sucursal_id integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = myappdb, public
as $$
declare
  v_cod integer;
  v_empre text := btrim(coalesce(p_cod_empre, ''));
  v_suc integer;
begin
  if not app_private.es_dueno_plataforma() then
    raise exception 'Solo el dueno de la plataforma puede usar esta opcion.' using errcode = '42501';
  end if;

  select cu.codusuario into v_cod from app_private.current_usuario() cu limit 1;
  if v_cod is null then
    raise exception 'No se encontro su usuario en el sistema.' using errcode = 'P0001';
  end if;

  if not exists (select 1 from myappdb.empresas e where e.cod_empre = v_empre) then
    raise exception 'La empresa % no existe.', v_empre using errcode = 'P0001';
  end if;

  select s.cod_sucursal into v_suc
  from myappdb.sucursales s
  where s.cod_empre = v_empre
    and (p_sucursal_id is null or s.cod_sucursal = p_sucursal_id)
  order by s.cod_sucursal
  limit 1;

  if v_suc is null then
    raise exception 'La empresa % no tiene sucursales. Cree una sucursal primero.', v_empre
      using errcode = 'P0001';
  end if;

  update myappdb.usuario u
     set cod_empre = v_empre,
         sucursalid = v_suc
   where u.codusuario = v_cod;

  return jsonb_build_object('cod_empre', v_empre, 'sucursalid', v_suc);
end;
$$;

revoke all on function myappdb.plataforma_entrar_empresa(text, integer) from public;
grant execute on function myappdb.plataforma_entrar_empresa(text, integer) to authenticated;

-- 7) Estado de acceso al iniciar sesion --------------------------------------
create or replace function myappdb.empresa_estado_acceso()
returns jsonb
language plpgsql
stable
security definer
set search_path = myappdb, public
as $$
declare
  v_empre text;
  v_row record;
begin
  if auth.uid() is null then
    return jsonb_build_object('permitido', false, 'motivo', 'No autenticado');
  end if;

  if app_private.es_dueno_plataforma() then
    return jsonb_build_object('permitido', true, 'dueno', true);
  end if;

  select cu.cod_empre into v_empre from app_private.current_usuario() cu limit 1;
  select e.nom_empre, e.activa, e.motivo_suspension
    into v_row
  from myappdb.empresas e
  where e.cod_empre = v_empre;

  if found and v_row.activa is false then
    return jsonb_build_object(
      'permitido', false,
      'dueno', false,
      'empresa', v_row.nom_empre,
      'motivo', v_row.motivo_suspension
    );
  end if;

  return jsonb_build_object('permitido', true, 'dueno', false);
end;
$$;

revoke all on function myappdb.empresa_estado_acceso() from public;
grant execute on function myappdb.empresa_estado_acceso() to authenticated;

commit;

notify pgrst, 'reload schema';
