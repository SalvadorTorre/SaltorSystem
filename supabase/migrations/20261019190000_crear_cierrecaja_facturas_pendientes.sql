-- Facturas a credito y pendientes de pago incluidas en cada cierre de caja.
--
-- Al cerrar la caja, las facturas cobradas quedan marcadas con fa_cierre en
-- myappdb.factura. Las de credito y las pendientes de pago no se marcan (siguen
-- abiertas), asi que se guarda aqui una foto de como estaban al momento del
-- cierre para poder consultarlas despues desde "Consulta de cierres".

begin;

create table if not exists myappdb.cierrecaja_facturas_pendientes (
  id bigint generated by default as identity primary key,
  idcierre integer not null,
  feccierre date,
  codsucursal integer,
  fa_codfact varchar(30) not null,
  fa_fecfact date,
  cliente varchar(255),
  vendedor varchar(255),
  tipo varchar(30),
  forma_pago varchar(100),
  estado varchar(30),
  valor numeric(18,2) not null default 0,
  creado_en timestamptz not null default now(),
  constraint cierrecaja_facturas_pendientes_unq unique (idcierre, fa_codfact)
);

comment on table myappdb.cierrecaja_facturas_pendientes is
  'Facturas a credito y pendientes de pago registradas al realizar cada cierre de caja.';
comment on column myappdb.cierrecaja_facturas_pendientes.idcierre is 'Numero del cierre (myappdb.cierrecaja.idcierre).';
comment on column myappdb.cierrecaja_facturas_pendientes.feccierre is 'Fecha del cierre.';
comment on column myappdb.cierrecaja_facturas_pendientes.fa_codfact is 'Numero de factura.';
comment on column myappdb.cierrecaja_facturas_pendientes.fa_fecfact is 'Fecha de la factura.';
comment on column myappdb.cierrecaja_facturas_pendientes.tipo is 'Factura o Conduce.';
comment on column myappdb.cierrecaja_facturas_pendientes.estado is 'CREDITO o Pendiente Pago al momento del cierre.';

create index if not exists idx_cierrecaja_facturas_pendientes_cierre
  on myappdb.cierrecaja_facturas_pendientes (idcierre);

create index if not exists idx_cierrecaja_facturas_pendientes_factura
  on myappdb.cierrecaja_facturas_pendientes (fa_codfact);

-- Mismo permiso que la tabla cierrecaja.
alter table myappdb.cierrecaja_facturas_pendientes enable row level security;

drop policy if exists cierrecaja_facturas_pendientes_all_permiso on myappdb.cierrecaja_facturas_pendientes;
create policy cierrecaja_facturas_pendientes_all_permiso
on myappdb.cierrecaja_facturas_pendientes
for all to authenticated
using (
  app_private.has_permission('caja.cuadrecaja', 'cerrar_caja')
)
with check (
  app_private.has_permission('caja.cuadrecaja', 'cerrar_caja')
);

grant select, insert, update, delete on table myappdb.cierrecaja_facturas_pendientes to authenticated;

commit;

notify pgrst, 'reload schema';
