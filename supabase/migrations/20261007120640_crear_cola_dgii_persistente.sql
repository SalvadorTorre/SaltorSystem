begin;

create table if not exists myappdb.cola_dgii (
  id bigint generated by default as identity primary key,
  fa_codempr varchar(20) not null,
  fa_codsucu integer not null,
  fa_codfact varchar(30) not null,
  fa_ncffact varchar(30),
  rnc_emisor varchar(20) not null,
  tipo_operacion varchar(20) not null default 'ENVIO',
  payload jsonb not null,
  estado varchar(30) not null default 'PENDIENTE',
  intentos integer not null default 0,
  max_intentos integer not null default 8,
  proximo_intento timestamptz not null default now(),
  bloqueado_hasta timestamptz,
  worker_id uuid,
  ultimo_http_status integer,
  ultimo_error text,
  respuesta jsonb,
  solicitado_por uuid not null default auth.uid(),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  procesado_en timestamptz,
  constraint cola_dgii_estado_check check (
    estado in ('PENDIENTE', 'PROCESANDO', 'REINTENTO', 'VERIFICAR', 'ACEPTADO', 'ACEPTADO_CONDICIONAL', 'RECHAZADO', 'ERROR', 'CANCELADO')
  ),
  constraint cola_dgii_tipo_check check (tipo_operacion in ('ENVIO', 'REENVIO')),
  constraint cola_dgii_intentos_check check (intentos >= 0 and max_intentos between 1 and 50),
  constraint cola_dgii_payload_check check (jsonb_typeof(payload -> 'scenarios') = 'array')
);

create unique index if not exists cola_dgii_factura_activa_uidx
  on myappdb.cola_dgii (fa_codempr, fa_codsucu, fa_codfact)
  where estado in ('PENDIENTE', 'PROCESANDO', 'REINTENTO', 'VERIFICAR');

create index if not exists cola_dgii_pendientes_idx
  on myappdb.cola_dgii (proximo_intento, creado_en)
  where estado in ('PENDIENTE', 'REINTENTO');

create index if not exists cola_dgii_tenant_idx
  on myappdb.cola_dgii (fa_codempr, fa_codsucu, creado_en desc);

alter table myappdb.cola_dgii enable row level security;

revoke all on table myappdb.cola_dgii from anon;
grant select on table myappdb.cola_dgii to authenticated;
grant usage, select on sequence myappdb.cola_dgii_id_seq to authenticated;

drop policy if exists cola_dgii_select_empresa on myappdb.cola_dgii;
create policy cola_dgii_select_empresa
on myappdb.cola_dgii
for select to authenticated
using (
  exists (
    select 1
    from app_private.current_usuario() cu
    where upper(btrim(coalesce(cola_dgii.fa_codempr, ''))) = upper(btrim(coalesce(cu.cod_empre, '')))
      and (
        cola_dgii.fa_codsucu = cu.sucursalid
        or coalesce(cu.idtipousuario, 0) = 1
        or app_private.has_any_permission(
          '[
            {"recurso":"contabilidad.reporte_607","accion":"ver"},
            {"recurso":"facturacion.factura","accion":"enviar_dgii"},
            {"recurso":"caja.cobrofact","accion":"enviar_dgii"}
          ]'::jsonb,
          cu.cod_empre,
          cu.sucursalid::text
        )
      )
  )
);

create or replace function myappdb.encolar_factura_dgii(
  p_empresa text,
  p_sucursal integer,
  p_factura text,
  p_encf text,
  p_rnc_emisor text,
  p_payload jsonb,
  p_tipo_operacion text default 'ENVIO'
)
returns myappdb.cola_dgii
language plpgsql
security definer
set search_path = pg_catalog, myappdb, app_private
as $$
declare
  v_usuario record;
  v_fila myappdb.cola_dgii;
begin
  if auth.uid() is null then
    raise exception 'Debe iniciar sesion para enviar a DGII' using errcode = '42501';
  end if;

  select * into v_usuario from app_private.current_usuario() limit 1;
  if v_usuario is null
     or upper(btrim(coalesce(p_empresa, ''))) <> upper(btrim(coalesce(v_usuario.cod_empre, ''))) then
    raise exception 'La factura no pertenece a la empresa del usuario' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from myappdb.factura f
    where f.fa_codfact::text = btrim(p_factura)
      and upper(btrim(coalesce(f.fa_codempr, ''))) = upper(btrim(p_empresa))
      and f.fa_codsucu = p_sucursal
  ) then
    raise exception 'No se encontro la factura % en la empresa y sucursal indicadas', p_factura;
  end if;

  if jsonb_typeof(p_payload -> 'scenarios') <> 'array'
     or jsonb_array_length(p_payload -> 'scenarios') = 0 then
    raise exception 'El comprobante DGII no contiene escenarios';
  end if;

  select * into v_fila
  from myappdb.cola_dgii q
  where q.fa_codempr = p_empresa
    and q.fa_codsucu = p_sucursal
    and q.fa_codfact = btrim(p_factura)
    and q.estado in ('PENDIENTE', 'PROCESANDO', 'REINTENTO', 'VERIFICAR')
  order by q.id desc
  limit 1;

  if found then
    return v_fila;
  end if;

  insert into myappdb.cola_dgii (
    fa_codempr, fa_codsucu, fa_codfact, fa_ncffact, rnc_emisor,
    payload, tipo_operacion, solicitado_por
  ) values (
    btrim(p_empresa), p_sucursal, btrim(p_factura), nullif(btrim(p_encf), ''),
    regexp_replace(coalesce(p_rnc_emisor, ''), '[^0-9]', '', 'g'),
    p_payload, upper(coalesce(nullif(btrim(p_tipo_operacion), ''), 'ENVIO')),
    auth.uid()
  )
  returning * into v_fila;

  update myappdb.factura
  set estado_envio_dgii = 'PENDIENTE',
      dgii_request_json = p_payload -> 'scenarios' -> 0,
      dgii_updated_at = now()
  where fa_codfact::text = btrim(p_factura)
    and upper(btrim(coalesce(fa_codempr, ''))) = upper(btrim(p_empresa))
    and fa_codsucu = p_sucursal;

  return v_fila;
end;
$$;

revoke all on function myappdb.encolar_factura_dgii(text, integer, text, text, text, jsonb, text) from public, anon;
grant execute on function myappdb.encolar_factura_dgii(text, integer, text, text, text, jsonb, text) to authenticated;

create or replace function myappdb.reclamar_cola_dgii(p_limite integer default 5)
returns setof myappdb.cola_dgii
language plpgsql
security definer
set search_path = pg_catalog, myappdb
as $$
declare
  v_worker uuid := gen_random_uuid();
begin
  return query
  with candidatas as (
    select q.id
    from myappdb.cola_dgii q
    where (
      q.estado in ('PENDIENTE', 'REINTENTO')
      or (q.estado = 'PROCESANDO' and q.bloqueado_hasta < now())
    )
      and q.proximo_intento <= now()
    order by q.proximo_intento, q.id
    for update skip locked
    limit least(greatest(coalesce(p_limite, 5), 1), 20)
  )
  update myappdb.cola_dgii q
  set estado = 'PROCESANDO',
      intentos = q.intentos + 1,
      bloqueado_hasta = now() + interval '3 minutes',
      worker_id = v_worker,
      actualizado_en = now()
  from candidatas c
  where q.id = c.id
  returning q.*;
end;
$$;

revoke all on function myappdb.reclamar_cola_dgii(integer) from public, anon, authenticated;
grant execute on function myappdb.reclamar_cola_dgii(integer) to service_role;

-- Ejecuta el trabajador cada minuto. verify_jwt=false permite que pg_cron lo
-- invoque; la funcion solo reclama trabajos ya autorizados en la base de datos.
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

do $$
declare
  v_job_id bigint;
begin
  select jobid into v_job_id from cron.job where jobname = 'procesar-cola-dgii';
  if v_job_id is not null then
    perform cron.unschedule(v_job_id);
  end if;

  perform cron.schedule(
    'procesar-cola-dgii',
    '* * * * *',
    $job$
      select net.http_post(
        url := 'https://saltor-supabase.tail67c2f6.ts.net/functions/v1/procesar-cola-facturas',
        headers := '{"Content-Type":"application/json"}'::jsonb,
        body := '{"limite":1}'::jsonb,
        timeout_milliseconds := 120000
      );
    $job$
  );
end $$;

commit;

notify pgrst, 'reload schema';
